import 'descriptor.dart';
import 'version.dart';

/// Generated Dart source files for one worker.
class DwiGeneratedSources {
  const DwiGeneratedSources({required this.worker, required this.proxies});

  /// Worker entrypoint source (`.dwi/generated_worker.dart` by default).
  final String worker;

  /// Typed caller proxies (`lib/dwi_tasks.g.dart` by default).
  final String proxies;
}

/// Emits deterministic worker entrypoints and typed proxies.
abstract final class DwiGenerator {
  /// Generates both files for [tasks].
  ///
  /// Output is byte-identical for the same tasks: no timestamps, no absolute
  /// paths, and a stable task/import order.
  static DwiGeneratedSources generate(
    List<DwiTaskDescriptor> tasks, {
    required String workerId,
    String target = 'js',
  }) {
    final sorted = List<DwiTaskDescriptor>.of(tasks)
      ..sort((a, b) {
        final byName = a.name.compareTo(b.name);
        if (byName != 0) return byName;
        return a.sourcePath.compareTo(b.sourcePath);
      });
    return DwiGeneratedSources(
      worker: _workerSource(sorted, workerId: workerId, target: target),
      proxies: _proxySource(sorted, workerId: workerId),
    );
  }

  static String _workerSource(
    List<DwiTaskDescriptor> tasks, {
    required String workerId,
    String target = 'js',
  }) {
    final taskPrefixes = _taskPrefixes(tasks);
    final typePrefixes = _typePrefixes(tasks);
    final codecs = _codecTypes(tasks);
    final ids = _codecIds(codecs);

    final buffer = StringBuffer()
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
      ..writeln('// Generated by dwi_builder $dwiBuilderVersion.')
      ..writeln('//')
      ..writeln(
        '// Every task is a static reference. A task name alone would be '
        'tree-shaken.',
      )
      ..writeln()
      ..writeln('// ignore_for_file: type=lint, avoid_relative_lib_imports')
      ..writeln();
    for (final import in _typeImports(typePrefixes)) {
      buffer.writeln(import);
    }
    buffer
      ..writeln("import 'package:dwi_core/dwi_core.dart';")
      ..writeln("import 'package:dwi_web/dwi_worker.dart';");
    for (final entry in taskPrefixes.entries) {
      buffer.writeln(
        "import '${_dartString(entry.key)}' as ${entry.value};",
      );
    }
    buffer
      ..writeln()
      ..writeln(
        'final Map<String, DwiWorkerTask> _tasks = '
        '<String, DwiWorkerTask>{',
      );
    for (final task in tasks) {
      final prefix = taskPrefixes[task.importUri]!;
      buffer.writeln(
        "  '${_dartString(task.name)}': ${_lambda(task, prefix, ids)},",
      );
    }
    buffer
      ..writeln('};')
      ..writeln()
      ..writeln('void main() {')
      ..writeln('  DwiWorkerRuntime.start(')
      ..writeln('    _tasks,')
      ..writeln("    workerId: '${_dartString(workerId)}',")
      ..writeln(
        "    backend: '${target == 'wasm' ? 'dart2wasm' : 'dart2js'}',",
      )
      ..writeln('  );')
      ..writeln('}')
      ..writeln();
    _writeDecoders(buffer, codecs, ids, typePrefixes);
    return buffer.toString();
  }

  static String _proxySource(
    List<DwiTaskDescriptor> tasks, {
    required String workerId,
  }) {
    final taskPrefixes = _taskPrefixes(tasks);
    final typePrefixes = _typePrefixes(tasks);
    final codecs = _codecTypes(tasks);
    final ids = _codecIds(codecs);

    final buffer = StringBuffer()
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
      ..writeln('// Generated by dwi_builder $dwiBuilderVersion.')
      ..writeln('//')
      ..writeln('// Import this file to call discovered tasks through DWI.')
      ..writeln()
      ..writeln('// ignore_for_file: type=lint')
      ..writeln();
    for (final import in _typeImports(typePrefixes)) {
      buffer.writeln(import);
    }
    buffer.writeln("import 'package:dwi/dwi.dart';");
    for (final entry in taskPrefixes.entries) {
      buffer.writeln(
        "import '${_dartString(entry.key)}' as ${entry.value};",
      );
    }
    buffer
      ..writeln()
      ..writeln('/// Task name → Dart function name for generated tasks.')
      ..writeln(
        'const Map<String, String> dwiGeneratedTasks = '
        '<String, String>{',
      );
    for (final task in tasks) {
      buffer.writeln(
        "  '${_dartString(task.name)}': '${_dartString(task.functionName)}',",
      );
    }
    buffer
      ..writeln('};')
      ..writeln()
      ..writeln('/// Worker id used by the generated manifest.')
      ..writeln(
        'const String dwiGeneratedWorkerId = '
        "'${_dartString(workerId)}';",
      )
      ..writeln()
      ..writeln('bool _dwiGeneratedTasksRegistered = false;')
      ..writeln()
      ..writeln('/// Registers native implementations for generated tasks.')
      ..writeln('///')
      ..writeln(
        '/// The web backend ignores this registry; native DWI runs the same '
        'task on an isolate.',
      )
      ..writeln('void _dwiRegisterGeneratedTasks() {')
      ..writeln('  if (_dwiGeneratedTasksRegistered) return;')
      ..writeln('  _dwiGeneratedTasksRegistered = true;');
    for (final task in tasks) {
      final prefix = taskPrefixes[task.importUri]!;
      buffer.writeln(
        "  Dwi.registerTask("
        "'${_dartString(task.name)}', ${_lambda(task, prefix, ids)});",
      );
    }
    buffer
      ..writeln('}')
      ..writeln()
      ..writeln('/// Typed proxies for `@DwiTask` functions.')
      ..writeln('///')
      ..writeln(
        '/// Every method routes through `Dwi.run`; workers are '
        'started lazily.',
      )
      ..writeln('abstract final class DwiTasks {');
    for (var index = 0; index < tasks.length; index++) {
      final task = tasks[index];
      if (index > 0) buffer.writeln();
      buffer
        ..writeln(
          '  /// Runs `${task.functionName}` in a DWI worker or '
          'isolate.',
        )
        ..writeln('  static ${_proxySignature(task, typePrefixes)} async {')
        ..writeln('    _dwiRegisterGeneratedTasks();');
      final call = task.takesInput
          ? "Dwi.run<Object?>('${_dartString(task.name)}', input)"
          : "Dwi.run<Object?>('${_dartString(task.name)}')";
      if (task.returnsVoid) {
        buffer
          ..writeln('    await $call;')
          ..writeln('  }');
      } else {
        buffer
          ..writeln('    final value = await $call;')
          ..writeln(
            "    return ${_decodeCall(task.output, 'value', "'result'", ids)};",
          )
          ..writeln('  }');
      }
    }
    buffer
      ..writeln('}')
      ..writeln();
    _writeDecoders(buffer, codecs, ids, typePrefixes);
    return buffer.toString();
  }

  static String _proxySignature(
    DwiTaskDescriptor task,
    Map<String, String> prefixes,
  ) {
    final parameter = task.takesInput
        ? '${task.input!.render(prefixes)} input'
        : '';
    final output = task.returnsVoid ? 'void' : task.output.render(prefixes);
    return 'Future<$output> ${task.functionName}($parameter)';
  }

  static Map<String, String> _taskPrefixes(List<DwiTaskDescriptor> tasks) {
    final prefixes = <String, String>{};
    for (final task in tasks) {
      if (prefixes.containsKey(task.importUri)) continue;
      prefixes[task.importUri] = 'task${prefixes.length}';
    }
    return prefixes;
  }

  static Map<String, String> _typePrefixes(List<DwiTaskDescriptor> tasks) {
    final uris = <String>{};
    void visit(DwiTypeDescriptor? type) {
      if (type == null || type.isDynamic || type.isVoid) return;
      final library = type.libraryUri;
      if (library != null && !type.isCore) uris.add(library);
      for (final argument in type.arguments) {
        visit(argument);
      }
    }

    for (final task in tasks) {
      visit(task.input);
      if (!task.returnsVoid) visit(task.output);
    }
    final sorted = uris.toList(growable: false)..sort();
    return <String, String>{
      for (var index = 0; index < sorted.length; index++)
        sorted[index]: 'dwi_t$index',
    };
  }

  static List<String> _typeImports(Map<String, String> prefixes) => <String>[
    for (final entry in prefixes.entries)
      "import '${_dartString(entry.key)}' as ${entry.value};",
  ];

  /// Every non-void, non-dynamic type that needs a decoder, including nested
  /// arguments and the non-nullable form of nullable types.
  static List<DwiTypeDescriptor> _codecTypes(
    List<DwiTaskDescriptor> tasks,
  ) {
    final byKey = <String, DwiTypeDescriptor>{};
    void add(DwiTypeDescriptor? type) {
      if (type == null || type.isDynamic || type.isVoid) return;
      if (byKey.containsKey(type.canonical)) return;
      byKey[type.canonical] = type;
      for (final argument in type.arguments) {
        add(argument);
      }
      if (type.nullable) add(type.nonNullable);
    }

    for (final task in tasks) {
      add(task.input);
      if (!task.returnsVoid) add(task.output);
    }
    final types = byKey.values.toList(growable: false)
      ..sort((a, b) => a.canonical.compareTo(b.canonical));
    return types;
  }

  static Map<String, int> _codecIds(List<DwiTypeDescriptor> types) => {
    for (var index = 0; index < types.length; index++)
      types[index].canonical: index,
  };

  static String _decodeCall(
    DwiTypeDescriptor type,
    String value,
    String path,
    Map<String, int> ids,
  ) {
    if (type.isDynamic) return value;
    return '_dwiDecode${ids[type.canonical]}($value, $path)';
  }

  static String _lambda(
    DwiTaskDescriptor task,
    String prefix,
    Map<String, int> ids,
  ) {
    final input = task.takesInput
        ? _decodeCall(task.input!, 'input', "'input'", ids)
        : '';
    final call = '$prefix.${task.functionName}($input)';
    if (!task.returnsVoid) {
      return '(Object? input) => $call';
    }
    if (task.returnsFuture) {
      return '(Object? input) async { await $call; return null; }';
    }
    return '(Object? input) { $call; return null; }';
  }

  static void _writeDecoders(
    StringBuffer buffer,
    List<DwiTypeDescriptor> types,
    Map<String, int> ids,
    Map<String, String> prefixes,
  ) {
    if (types.isEmpty) return;
    buffer.writeln('// --- Generated payload decoders ---');
    buffer.writeln();
    for (final type in types) {
      buffer.writeln(
        '${type.render(prefixes)} _dwiDecode${ids[type.canonical]}('
        'Object? value, String path) {',
      );
      for (final line in _decoderBody(type, ids, prefixes)) {
        buffer.writeln(line);
      }
      buffer
        ..writeln('}')
        ..writeln();
    }
  }

  static List<String> _decoderBody(
    DwiTypeDescriptor type,
    Map<String, int> ids,
    Map<String, String> prefixes,
  ) {
    if (type.nullable) {
      return <String>[
        '  if (value == null) return null;',
        "  return ${_decodeCall(type.nonNullable, 'value', 'path', ids)};",
      ];
    }
    if (type.isObject) {
      return <String>[
        '  if (value == null) {',
        "    throw DwiSerializationException("
        "'\$path: expected Object, got Null');",
        '  }',
        '  return value;',
      ];
    }

    switch (type.name) {
      case 'int':
        return <String>[
          '  if (value is int) return value;',
          // A dart2wasm worker receives JS numbers as `double`; an integral
          // value is still an int and must be accepted (ADR-018).
          '  if (value is double && value.isFinite && '
              'value == value.truncateToDouble()) {',
          '    return value.toInt();',
          '  }',
          "  throw DwiSerializationException("
          "'\$path: expected int, got \${value.runtimeType}');",
        ];
      case 'double':
        return <String>[
          '  if (value is num) return value.toDouble();',
          "  throw DwiSerializationException("
          "'\$path: expected double, got \${value.runtimeType}');",
        ];
      case 'num':
        return <String>[
          '  if (value is num) return value;',
          "  throw DwiSerializationException("
          "'\$path: expected num, got \${value.runtimeType}');",
        ];
      case 'String':
        return <String>[
          '  if (value is String) return value;',
          "  throw DwiSerializationException("
          "'\$path: expected String, got \${value.runtimeType}');",
        ];
      case 'bool':
        return <String>[
          '  if (value is bool) return value;',
          "  throw DwiSerializationException("
          "'\$path: expected bool, got \${value.runtimeType}');",
        ];
      case 'List':
        return _collectionBody(type, ids, prefixes, isSet: false);
      case 'Set':
        return _collectionBody(type, ids, prefixes, isSet: true);
      case 'Map':
        return _mapBody(type, ids, prefixes);
      case 'ByteData':
        return _byteDataBody(type, prefixes);
      case 'ByteBuffer':
        return _byteBufferBody(type, prefixes);
    }

    final element = _typedDataElementType[type.name];
    if (type.isCore == false &&
        type.libraryUri == 'dart:typed_data' &&
        element != null) {
      return _typedDataBody(type, element, prefixes);
    }

    if (type.name == 'DwiTransferableBytes' &&
        (type.libraryUri?.startsWith('package:dwi_core/') ?? false)) {
      // Already wrapped by the transport; only the type has to hold.
      final prefix = prefixes[type.libraryUri!] ?? '';
      final name = prefix.isEmpty
          ? 'DwiTransferableBytes'
          : '$prefix.DwiTransferableBytes';
      return <String>[
        '  if (value is $name) return value;',
        "  throw DwiSerializationException("
        "'\$path: expected DwiTransferableBytes, got \${value.runtimeType}');",
      ];
    }

    return <String>[
      '  if (value is ${type.render(prefixes)}) return value;',
      "  throw DwiSerializationException("
      "'\$path: expected ${type.canonical}, got \${value.runtimeType}');",
    ];
  }

  static List<String> _collectionBody(
    DwiTypeDescriptor type,
    Map<String, int> ids,
    Map<String, String> prefixes, {
    required bool isSet,
  }) {
    final elementType = type.arguments.isEmpty
        ? DwiTypeDescriptor.dynamicType
        : type.arguments.first;
    final rendered = type.render(prefixes);
    final elementRendered = elementType.render(prefixes);
    final lines = <String>[
      if (isSet)
        '  if (value is! Iterable) {'
      else
        '  if (value is! List) {',
      "    throw DwiSerializationException("
      "'\$path: expected $rendered, got \${value.runtimeType}');",
      '  }',
      if (isSet)
        '  final result = <$elementRendered>{};'
      else
        '  final result = <$elementRendered>[];',
      if (isSet) '  var index = 0;' else '  for (var index = 0; index < value.length; index++) {',
      if (isSet) '  for (final item in value) {' else '    final item = value[index];',
    ];
    if (isSet) {
      lines.add(
        '    result.add(${_decodeCall(elementType, 'item', "'\$path[\$index]'", ids)});',
      );
      lines
        ..add('    index++;')
        ..add('  }');
    } else {
      lines.add(
        '    result.add(${_decodeCall(elementType, 'item', "'\$path[\$index]'", ids)});',
      );
      lines.add('  }');
    }
    lines.add('  return result;');
    return lines;
  }

  static List<String> _mapBody(
    DwiTypeDescriptor type,
    Map<String, int> ids,
    Map<String, String> prefixes,
  ) {
    final key = type.arguments.isNotEmpty
        ? type.arguments[0]
        : const DwiTypeDescriptor(name: 'String', libraryUri: 'dart:core');
    final value = type.arguments.length > 1
        ? type.arguments[1]
        : DwiTypeDescriptor.dynamicType;
    final rendered = type.render(prefixes);
    return <String>[
      '  if (value is! Map) {',
      "    throw DwiSerializationException("
      "'\$path: expected $rendered, got \${value.runtimeType}');",
      '  }',
      '  final result = <${key.render(prefixes)}, ${value.render(prefixes)}>{};',
      '  for (final entry in value.entries) {',
      "    final key = ${_decodeCall(key, 'entry.key', "'\$path[key]'", ids)};",
      "    result[key] = "
          "${_decodeCall(value, 'entry.value', "'\$path[\$key]'", ids)};",
      '  }',
      '  return result;',
    ];
  }

  static List<String> _typedDataBody(
    DwiTypeDescriptor type,
    String elementType,
    Map<String, String> prefixes,
  ) {
    final rendered = type.render(prefixes);
    final isDouble = elementType == 'double';
    return <String>[
      '  if (value is $rendered) return value;',
      '  if (value is List) {',
      '    final result = <$elementType>[];',
      '    for (var index = 0; index < value.length; index++) {',
      '      final item = value[index];',
      if (isDouble)
        '      if (item is num) {'
      else
        '      if (item is int) {',
      if (isDouble)
        '        result.add(item.toDouble());'
      else
        '        result.add(item);',
      '      } else {',
      "        throw DwiSerializationException("
          "'\$path[\$index]: expected $elementType, got \${item.runtimeType}');",
      '      }',
      '    }',
      '    return $rendered.fromList(result);',
      '  }',
      "  throw DwiSerializationException("
      "'\$path: expected $rendered, got \${value.runtimeType}');",
    ];
  }

  static List<String> _byteDataBody(
    DwiTypeDescriptor type,
    Map<String, String> prefixes,
  ) {
    final rendered = type.render(prefixes);
    final typedData = prefixes['dart:typed_data'];
    return <String>[
      '  if (value is $rendered) return value;',
      '  if (value is $typedData.ByteBuffer) return value.asByteData();',
      '  if (value is $typedData.TypedData) return $typedData.ByteData.sublistView(value);',
      '  if (value is List) {',
      '    final result = <int>[];',
      '    for (var index = 0; index < value.length; index++) {',
      '      final item = value[index];',
      '      if (item is! int) {',
      "        throw DwiSerializationException("
          "'\$path[\$index]: expected int, got \${item.runtimeType}');",
      '      }',
      '      result.add(item);',
      '    }',
      '    return $typedData.ByteData.sublistView($typedData.Uint8List.fromList(result));',
      '  }',
      "  throw DwiSerializationException("
      "'\$path: expected ByteData, got \${value.runtimeType}');",
    ];
  }

  static List<String> _byteBufferBody(
    DwiTypeDescriptor type,
    Map<String, String> prefixes,
  ) {
    final rendered = type.render(prefixes);
    final typedData = prefixes['dart:typed_data'];
    return <String>[
      '  if (value is $rendered) return value;',
      '  if (value is $typedData.ByteData) return value.buffer;',
      '  if (value is $typedData.TypedData) return value.buffer;',
      '  if (value is List) {',
      '    final result = <int>[];',
      '    for (var index = 0; index < value.length; index++) {',
      '      final item = value[index];',
      '      if (item is! int) {',
      "        throw DwiSerializationException("
          "'\$path[\$index]: expected int, got \${item.runtimeType}');",
      '      }',
      '      result.add(item);',
      '    }',
      '    return $typedData.Uint8List.fromList(result).buffer;',
      '  }',
      "  throw DwiSerializationException("
      "'\$path: expected ByteBuffer, got \${value.runtimeType}');",
    ];
  }

  static const Map<String, String> _typedDataElementType =
      <String, String>{
        'Int8List': 'int',
        'Uint8List': 'int',
        'Uint8ClampedList': 'int',
        'Int16List': 'int',
        'Uint16List': 'int',
        'Int32List': 'int',
        'Uint32List': 'int',
        'Int64List': 'int',
        'Uint64List': 'int',
        'Float32List': 'double',
        'Float64List': 'double',
      };

  static String _dartString(String value) =>
      value.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
}
